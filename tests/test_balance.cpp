/*
 * Balance runner (PART 30, 31.3, 54): every Adventure stage played by human-paced
 * bots (reaction time, tap rate, imprecise placements) on two skill profiles.
 * Produces tests/build/balance_report.md (win rates, clear times against par,
 * scores against the S target, suggested calibration) and checks the difficulty curve.
 */
#include "bm_test.h"

#include "bm_bot.h"
#include "bm_session.h"

#include <cstdio>

using namespace bm;

namespace
{
    struct profile
    {
        const char* name;
        bot_pace pace;
        difficulty diff;
        int seeds;
    };

    // Skilled players are measured on STANDARD (the intended challenge), casual players on BEGINNER.
    constexpr profile profiles[2] = {
        { "skilled", { 14, 4, 4 }, difficulty::standard, 4 },
        { "casual", { 26, 7, 12 }, difficulty::beginner, 3 },
    };

    struct outcome
    {
        bool won = false;
        uint32_t frames = 0;
        uint32_t score = 0;
        int invalid = 0;
    };

    outcome play_stage(const stage_def& st, const profile& pr, uint32_t seed)
    {
        static session s;
        static bot b;
        s.start(make_stage_config(st, pr.diff, seed));
        b.reset(bot_strategy::resource_aware, seed * 13 + 5);
        b.set_pace(pr.pace);
        outcome o;
        constexpr int max_frames = 60 * 60 * 15;
        for(int f = 0; f < max_frames; ++f)
        {
            if(s.state() == session_state::won || s.state() == session_state::lost)
            {
                break;
            }
            s.update(b.next(s));
            event e;
            while(s.events().pop(e))
            {
            }
            o.invalid += s.validate() ? 1 : 0;
        }
        o.won = s.state() == session_state::won;
        o.frames = s.stats().frames;
        o.score = s.score();
        return o;
    }
}

BM_TEST(balance, human_paced_stage_report)
{
    FILE* report = std::fopen("tests/build/balance_report.md", "w");
    if(report)
    {
        std::fprintf(report, "# Balance report (generated by tests/test_balance.cpp)\n\n");
        std::fprintf(report, "Human-paced bots. Skilled (STANDARD difficulty): 14-21 frame reaction, a tap every 4 frames, ");
        std::fprintf(report, "4%% misplaced pieces, %d seeds. Casual (BEGINNER difficulty): 26-39 frame reaction, ",
                     profiles[0].seeds);
        std::fprintf(report, "a tap every 7 frames, 12%% misplaced pieces, %d seeds.\n\n", profiles[1].seeds);
        std::fprintf(report, "Suggested values: par = 2.5 x skilled clear time (rounded up to 10 s); ");
        std::fprintf(report, "S target = 0.85 x skilled score (rounded to 500).\n\n");
        std::fprintf(report, "| Stage | Name | Par (s) | S target | Skilled wins | Skilled time (s) | Skilled score | ");
        std::fprintf(report, "Casual wins | Casual time (s) | Suggested par | Suggested S |\n");
        std::fprintf(report, "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n");
    }
    uint32_t boss_time[7] = {};
    int boss_wins[7][2] = {};
    int skilled_wins = 0;
    int casual_wins = 0;
    int skilled_w1 = 0;
    int casual_w12 = 0;
    int invalid = 0;
    for(int w = 1; w <= 6; ++w)
    {
        for(int i = 1; i <= 5; ++i)
        {
            const stage_def& st = stage(w, i);
            int wins[2] = {};
            uint32_t time_sum[2] = {};
            uint32_t score_sum = 0;
            for(int p = 0; p < 2; ++p)
            {
                for(uint32_t seed = 1; seed <= uint32_t(profiles[p].seeds); ++seed)
                {
                    const outcome o = play_stage(st, profiles[p], seed * 101u + uint32_t(w * 7 + i));
                    invalid += o.invalid;
                    if(o.won)
                    {
                        ++wins[p];
                        time_sum[p] += o.frames / 60;
                        if(p == 0)
                        {
                            score_sum += o.score;
                        }
                    }
                }
            }
            skilled_wins += wins[0];
            casual_wins += wins[1];
            skilled_w1 += w == 1 ? wins[0] : 0;
            casual_w12 += w <= 2 ? wins[1] : 0;
            const uint32_t t0 = wins[0] ? time_sum[0] / uint32_t(wins[0]) : 0;
            const uint32_t t1 = wins[1] ? time_sum[1] / uint32_t(wins[1]) : 0;
            const uint32_t sc = wins[0] ? score_sum / uint32_t(wins[0]) : 0;
            if(st.boss)
            {
                boss_time[st.boss] = t0;
                boss_wins[st.boss][0] = wins[0];
                boss_wins[st.boss][1] = wins[1];
            }
            const uint32_t par = t0 ? ((t0 * 5 / 2 + 9) / 10) * 10 : st.par_seconds;
            const uint32_t s_target = sc ? ((sc * 85 / 100 + 250) / 500) * 500 : st.rank_score;
            bmtest::note("balance %d-%d %-22s par %3u S %6u | skilled %d/%d %4us %6u | casual %d/%d %4us | "
                         "suggest par %u S %u", w, i, st.name, st.par_seconds, st.rank_score, wins[0],
                         profiles[0].seeds, t0, sc, wins[1], profiles[1].seeds, t1, par, s_target);
            if(report)
            {
                std::fprintf(report, "| %d-%d | %s | %u | %u | %d/%d | %u | %u | %d/%d | %u | %u | %u |\n", w, i,
                             st.name, st.par_seconds, st.rank_score, wins[0], profiles[0].seeds, t0, sc, wins[1],
                             profiles[1].seeds, t1, par, s_target);
            }
        }
    }
    if(report)
    {
        std::fprintf(report, "\nTotals: skilled %d/%d, casual %d/%d.\n", skilled_wins, 30 * profiles[0].seeds,
                     casual_wins, 30 * profiles[1].seeds);
        std::fprintf(report, "\n## Bosses: HP against damage (PART 20.1)\n\n");
        std::fprintf(report, "| Boss | HP | Skilled wins | Skilled fight (s) | Damage / min (skilled) | ");
        std::fprintf(report, "Typical player fight (s, 2.5x) | Casual wins |\n|---|---:|---:|---:|---:|---:|---:|\n");
        for(int id = 1; id <= 6; ++id)
        {
            const uint32_t t = boss_time[id];
            std::fprintf(report, "| %s | %d | %d/%d | %u | %u | %u | %d/%d |\n", boss(id).name, int(boss(id).hp),
                         boss_wins[id][0], profiles[0].seeds, t, t ? uint32_t(boss(id).hp) * 60u / t : 0u, t * 5 / 2,
                         boss_wins[id][1], profiles[1].seeds);
        }
        std::fclose(report);
    }
    CHECK_EQ(invalid, 0);
    bmtest::note("balance totals: skilled %d/%d (world 1: %d/%d), casual %d/%d (worlds 1-2: %d/%d)", skilled_wins,
                 30 * profiles[0].seeds, skilled_w1, 5 * profiles[0].seeds, casual_wins, 30 * profiles[1].seeds,
                 casual_w12, 10 * profiles[1].seeds);
    CHECK(skilled_w1 * 100 >= 5 * profiles[0].seeds * 90);      // World 1 teaches: competent players clear it
    CHECK(casual_w12 * 100 >= 10 * profiles[1].seeds * 60);     // Beginner keeps worlds 1-2 open to casual players
    CHECK(skilled_wins * 100 >= 30 * profiles[0].seeds * 70);   // the full campaign is fair for skilled players
}

BM_TEST(balance, ability_efficiency_report)
{
    // Chaos Arcade (with its environment events), skilled pace, one ability equipped at a time against none.
    constexpr int seeds = 3;
    constexpr int frames = 60 * 60 * 3;
    static session s;
    static bot b;
    FILE* report = std::fopen("tests/build/ability_report.md", "w");
    if(report)
    {
        std::fprintf(report, "# Ability efficiency (generated by tests/test_balance.cpp)\n\n");
        std::fprintf(report, "Chaos Arcade with environment events, skilled-pace resource-aware bot, %d seeds x 3 minutes, ",
                     seeds);
        std::fprintf(report, "one ability equipped. The bot fires abilities by simple rules (Shape Shift is not modelled).\n\n");
        std::fprintf(report, "| Ability | Cost | CD | Uses / run | Rows / run | Score / run | Losses | Score vs none |\n");
        std::fprintf(report, "|---|---:|---:|---:|---:|---:|---:|---:|\n");
    }
    uint64_t baseline = 0;
    int invalid = 0;
    for(int a = -1; a < cfg::ability_count; ++a)
    {
        int uses = 0;
        int rows = 0;
        int losses = 0;
        uint64_t score = 0;
        for(uint32_t seed = 1; seed <= uint32_t(seeds); ++seed)
        {
            session_config c;
            c.mode = game_mode::arcade;
            c.seed = seed * 4099u;
            c.endless = true;
            c.stage = &arcade_stage();
            c.loadout[0] = uint8_t(a < 0 ? 0 : a);
            c.loadout_count = a < 0 ? 0 : 1;
            s.start(c);
            b.reset(bot_strategy::resource_aware, seed * 3 + 1);
            b.set_pace(profiles[0].pace);
            for(int f = 0; f < frames && s.state() != session_state::lost; ++f)
            {
                s.update(b.next(s));
                event e;
                while(s.events().pop(e)) {}
                invalid += s.validate() ? 1 : 0;
            }
            uses += s.stats().abilities_used;
            rows += s.lines();
            score += s.score();
            losses += s.state() == session_state::lost ? 1 : 0;
        }
        if(a < 0)
        {
            baseline = score;
        }
        const char* name = a < 0 ? "(none)" : "";
        static constexpr const char* names[cfg::ability_count] = {
            "LASER BEAM", "TIME FREEZE", "GRAVITY PULSE", "SHAPE SHIFT", "NUCLEAR BURST", "SHIELD MATRIX",
            "CHAIN SPARK", "EMERGENCY VENT"
        };
        if(a >= 0)
        {
            name = names[a];
        }
        const int delta = baseline ? int((int64_t(score) - int64_t(baseline)) * 100 / int64_t(baseline)) : 0;
        bmtest::note("ability %-15s uses %5.1f rows %5.1f score %8u losses %d (%+d%% vs none)", name,
                     double(uses) / seeds, double(rows) / seeds, uint32_t(score / seeds), losses, delta);
        if(report)
        {
            std::fprintf(report, "| %s | %d | %d | %.1f | %.1f | %u | %d/%d | %+d%% |\n", name,
                         a < 0 ? 0 : cfg::ability_cost[a], a < 0 ? 0 : cfg::ability_cooldown[a], double(uses) / seeds,
                         double(rows) / seeds, uint32_t(score / seeds), losses, seeds, delta);
        }
    }
    if(report)
    {
        std::fclose(report);
    }
    CHECK_EQ(invalid, 0);
}
