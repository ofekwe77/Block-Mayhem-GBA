"""Writes tests/emu/audio.txt: every music track (and its Overheat arrangement) must start, keep playing past
its loop point (looping tracks) or end (one-shots), and every sound effect must be audible. Durations come
from the XM headers so the scenario follows the music generator."""
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# music_id order of src/bm_audio.h (1-based) -> module file
TRACKS = [
    (1, 'mus_title'), (2, 'mus_menu'), (3, 'mus_w1'), (4, 'mus_w2'), (5, 'mus_w3'), (6, 'mus_w4'), (7, 'mus_w5'),
    (8, 'mus_w6'), (9, 'mus_boss'), (10, 'mus_final'), (11, 'mus_victory'), (12, 'mus_gameover'),
    (13, 'mus_ending'), (14, 'mus_classic'),
]
ONE_SHOTS = {11, 12}
SFX_COUNT = 44
MUSIC_MIN_RMS = 800
SFX_MIN_RMS = 100


def duration_frames(name):
    d = open(os.path.join(ROOT, 'audio', name + '.xm'), 'rb').read()
    hsize = struct.unpack_from('<I', d, 60)[0]
    songlen, _restart, _channels, patterns, _instruments, _flags, tempo, bpm = struct.unpack_from('<HHHHHHHH', d, 64)
    order = list(d[80:80 + songlen])
    off = 60 + hsize
    rows = []
    for _ in range(patterns):
        plen = struct.unpack_from('<I', d, off)[0]
        prow = struct.unpack_from('<H', d, off + 5)[0]
        psize = struct.unpack_from('<H', d, off + 7)[0]
        rows.append(prow)
        off += plen + psize
    seconds = sum(rows[o] for o in order) * tempo * 2.5 / bpm
    return int(seconds * 60 + 0.5)


def main():
    out = ['# Generated by tools/gen_audio_scenario.py - every track and sound effect on the real ROM.',
           '# Looping tracks are sampled at the start and again 3 s past their loop point; one-shots must stop.',
           'frames 40', 'tap START', 'wait scene == 3 120', 'frames 30']
    for mid, name in TRACKS:
        length = duration_frames(name)
        loop = 0 if mid in ONE_SHOTS else 1
        out.append('# %s (%d frames)' % (name, length))
        out += ['cmd 11 %d 0 %d' % (mid, loop), 'frames 30', 'audio_begin', 'frames 120',
                'audio_check %s_start %d' % (name, MUSIC_MIN_RMS)]
        if loop:
            out += ['frames %d' % (length - 150 + 180), 'audio_begin', 'frames 120',
                    'audio_check %s_after_loop %d' % (name, MUSIC_MIN_RMS)]
            if os.path.exists(os.path.join(ROOT, 'audio', name + '_hot.xm')):
                out += ['cmd 11 %d 1 1' % mid, 'frames 30', 'audio_begin', 'frames 120',
                        'audio_check %s_hot %d' % (name, MUSIC_MIN_RMS)]
        else:
            out += ['frames %d' % (length - 150 + 120), 'audio_begin', 'frames 60',
                    'audio_check %s_ended 0 150' % name]
    out.append('# Sound effects over silence.')
    out += ['cmd 11 1 0 0', 'frames 2']
    out.append('frames %d' % (duration_frames('mus_title') + 60))
    for sid in range(SFX_COUNT):
        out += ['cmd 12 %d' % sid, 'audio_begin', 'frames 24', 'audio_check sfx_%d %d' % (sid, SFX_MIN_RMS), 'frames 8']
    out += ['print error_code sfx_count', 'expect error_code == 0']
    path = os.path.join(ROOT, 'tests', 'emu', 'audio.txt')
    with open(path, 'w', newline='\n', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote tests/emu/audio.txt')


if __name__ == '__main__':
    main()
