"""Generates tests/emu/stages_w1.txt .. stages_w6.txt: the emulator half of the 30-stage validation
(PART 50.10, 56.4). Each scenario boots a fresh console, then plays the world's five stages in order with
the diagnostic autoplay bot on the real ROM and checks, per stage:
  - the stage loads into gameplay and its intro hands over to play,
  - no internal error is flagged while it runs (the ROM validates the session invariants),
  - the stage can be won under its real rules (objectives, hazards, boss phases),
  - the results screen follows and campaign progression records the clear.
Failure triggering and "idling never wins" are proven for all 30 stages by the host test
stages.every_stage_can_be_lost_and_idling_never_wins.

Run: python3 tools/gen_stage_scenarios.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "emu")

# Game-time budget per stage for the bot (frames). Boss fights get more.
STAGE_FRAMES = 15000
BOSS_FRAMES = 30000


def scenario(world):
    lines = [
        "# Generated by tools/gen_stage_scenarios.py - do not edit.",
        "# Emulator validation of World %d's five stages (PART 50.10, 56.4): load, play to victory with the" % world,
        "# autoplay bot, results screen, campaign progression. session_state: 1 playing, 3 won, 4 lost.",
        "frames 40",
        "tap START",
        "wait scene == 3 120",
        "frames 30",
    ]
    for index in range(1, 6):
        seed = world * 100 + index
        limit = BOSS_FRAMES if index == 5 else STAGE_FRAMES
        lines += [
            "# Stage %d-%d" % (world, index),
            "cmd 1 %d %d %d 1" % (world, index, seed),
            "wait scene == 7 300",
            "wait stage == %d 300" % (world * 10 + index),
            "wait session_state == 1 600",
            "frames 200",
            "shot stage_%d_%d" % (world, index),
            "expect error_code == 0",
            "wait session_state >= 3 %d" % limit,
            "print stage session_state score lines boss_phase max_chain",
            "expect session_state == 3",
            "wait scene == 8 900",
            "expect stages_cleared == %d" % index,
            "expect error_code == 0",
        ]
    if world < 6:
        lines.append("expect worlds_unlocked == %d" % (world + 1))
    # Every text kept its colour: no sprite palette exhaustion anywhere in the world.
    lines.append("expect text_failures == 0")
    return "\n".join(lines) + "\n"


def main():
    for world in range(1, 7):
        path = os.path.join(OUT, "stages_w%d.txt" % world)
        with open(path, "w", newline="\n", encoding="utf-8") as f:
            f.write(scenario(world))
    print("wrote tests/emu/stages_w1..6.txt")


if __name__ == "__main__":
    main()
