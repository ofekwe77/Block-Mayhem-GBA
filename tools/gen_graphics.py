"""Generates every BLOCK MAYHEM graphic asset (original pixel art) into graphics/
plus generated C++ headers into include/. Run: python3 tools/gen_graphics.py
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "gfx"))

from bmp import write_bmp, write_json  # noqa: E402
import font  # noqa: E402
import tiles  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GFX = os.path.join(ROOT, "graphics")
INC = os.path.join(ROOT, "include")


def out(name):
    return os.path.join(GFX, name)


def write_header(name, text):
    path = os.path.join(INC, name)
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_graphics.py - do not edit.\n")
        f.write(text)


def gen_board_tiles():
    tile_list, names = tiles.build()
    n = len(tile_list)
    width = 8 * n
    pixels = [[0] * width for _ in range(8)]
    for i, t in enumerate(tile_list):
        for y in range(8):
            for x in range(8):
                pixels[y][i * 8 + x] = t[y][x]
    gray = [(i * 16, i * 16, i * 16) for i in range(16)]
    write_bmp(out("board_tiles.bmp"), width, 8, pixels, gray, bpp=4)
    write_json(out("board_tiles.json"), {"type": "regular_bg_tiles", "bpp_mode": "bpp_4"})

    pal = tiles.palette()
    write_bmp(out("board_palette.bmp"), 8, 8, [[0] * 8 for _ in range(8)], pal, bpp=8)
    write_json(out("board_palette.json"), {"type": "bg_palette", "bpp_mode": "bpp_4", "colors_count": len(pal)})

    lines = ["#ifndef BM_TILE_IDS_H\n#define BM_TILE_IDS_H\n\nnamespace bm::tile\n{\n"]
    for i, nm in enumerate(names):
        lines.append("    constexpr int %s = %d;\n" % (nm.lower(), i))
    lines.append("    constexpr int count = %d;\n}\n\n#endif\n" % n)
    write_header("bm_tile_ids.h", "".join(lines))
    return n


def gen_fonts():
    px, widths, extra = font.small_font()
    pal = [(0, 0, 0), (248, 248, 248), (16, 16, 48)] + [(0, 0, 0)] * 13
    write_bmp(out("font_small.bmp"), 8, len(px), px, pal, bpp=4)
    write_json(out("font_small.json"), {"type": "sprite", "height": 8})

    bpx, bwidths, _ = font.big_font()
    bpal = [(0, 0, 0), (255, 248, 200), (24, 8, 32), (255, 160, 32), (255, 255, 255)] + [(0, 0, 0)] * 11
    write_bmp(out("font_big.bmp"), 16, len(bpx), bpx, bpal, bpp=4)
    write_json(out("font_big.json"), {"type": "sprite", "height": 16})

    def font_header(guard, item, ns_name, ws, extra_chars, cell):
        s = []
        s.append("#ifndef %s\n#define %s\n\n" % (guard, guard))
        s.append('#include "bn_sprite_font.h"\n#include "bn_utf8_characters_map.h"\n')
        s.append('#include "bn_sprite_items_%s.h"\n\nnamespace bm::fonts\n{\n' % item)
        s.append("    constexpr bn::utf8_character %s_utf8[] = { " % ns_name)
        s.append(", ".join('"%s"' % c for c in extra_chars))
        s.append(" };\n\n")
        s.append("    constexpr int8_t %s_widths[] = {\n        " % ns_name)
        s.append(", ".join(str(min(cell, w)) for w in ws))
        s.append("\n    };\n\n")
        s.append("    constexpr bn::span<const bn::utf8_character> %s_utf8_span(%s_utf8);\n" % (ns_name, ns_name))
        s.append("    constexpr auto %s_utf8_map = bn::utf8_characters_map<%s_utf8_span>();\n\n" % (ns_name, ns_name))
        s.append("    constexpr bn::sprite_font %s(bn::sprite_items::%s, %s_utf8_map.reference(), %s_widths);\n"
                 % (ns_name, item, ns_name, ns_name))
        s.append("}\n\n#endif\n")
        return "".join(s)

    write_header("bm_font_small.h", font_header("BM_FONT_SMALL_H", "font_small", "small", widths, extra, 8))
    write_header("bm_font_big.h", font_header("BM_FONT_BIG_H", "font_big", "big", bwidths, extra, 16))

    tpx, twidths, _ = font.tiny_font()
    write_bmp(out("font_tiny.bmp"), 8, len(tpx), tpx, pal, bpp=4)
    write_json(out("font_tiny.json"), {"type": "sprite", "height": 8})
    write_header("bm_font_tiny.h", font_header("BM_FONT_TINY_H", "font_tiny", "tiny", twidths, extra, 8))

    # Text colour palettes (index 1 = text, index 2 = shadow/outline).
    text_colors = {
        "white": [(248, 248, 248), (16, 16, 48)],
        "yellow": [(255, 224, 64), (64, 24, 0)],
        "red": [(255, 80, 64), (48, 0, 8)],
        "cyan": [(96, 232, 255), (0, 24, 56)],
        "green": [(120, 248, 112), (0, 40, 8)],
        "orange": [(255, 152, 40), (56, 16, 0)],
        "gray": [(150, 150, 170), (16, 16, 32)],
        "violet": [(208, 136, 255), (32, 0, 56)],
    }
    for name, (fg, bg) in text_colors.items():
        pal = [(0, 0, 0), fg, bg] + [(0, 0, 0)] * 13
        write_bmp(out("pal_text_%s.bmp" % name), 8, 8, [[0] * 8 for _ in range(8)], pal, bpp=4)
        write_json(out("pal_text_%s.json" % name), {"type": "sprite_palette", "bpp_mode": "bpp_4"})

    big_palettes = {
        "fire": [(255, 248, 160), (40, 8, 16), (255, 112, 24), (255, 255, 255)],
        "ice": [(232, 248, 255), (8, 24, 56), (96, 176, 255), (255, 255, 255)],
        "gold": [(255, 240, 120), (48, 24, 0), (232, 152, 24), (255, 255, 255)],
        "toxic": [(208, 255, 120), (8, 32, 8), (64, 200, 72), (255, 255, 255)],
        "neon": [(255, 160, 255), (32, 0, 48), (176, 64, 255), (255, 255, 255)],
        "steel": [(232, 236, 248), (16, 16, 32), (128, 136, 168), (255, 255, 255)],
        "blood": [(255, 120, 120), (40, 0, 8), (200, 24, 40), (255, 255, 255)],
    }
    for name, cols in big_palettes.items():
        pal = [(0, 0, 0)] + cols + [(0, 0, 0)] * 11
        write_bmp(out("pal_big_%s.bmp" % name), 8, 8, [[0] * 8 for _ in range(8)], pal, bpp=4)
        write_json(out("pal_big_%s.json" % name), {"type": "sprite_palette", "bpp_mode": "bpp_4"})


def main():
    os.makedirs(GFX, exist_ok=True)
    os.makedirs(INC, exist_ok=True)
    n = gen_board_tiles()
    gen_fonts()
    import sprites  # noqa: E402
    import backgrounds  # noqa: E402
    import bosses  # noqa: E402
    sprites.generate(GFX, write_bmp, write_json)
    backgrounds.generate(GFX, INC, write_bmp, write_json)
    bosses.generate(GFX, write_bmp, write_json)
    print("graphics generated (%d board tiles)" % n)


if __name__ == "__main__":
    main()
