ORDER = [chr(c) for c in range(32, 127)]


def glyph(ch):
    if "a" <= ch <= "z":
        ch = ch.upper()
    rows = G.get(ch)
    if rows is None:
        rows = G["?"]
    return rows


def glyph_width(rows):
    return max([len(r) for r in rows] + [0])


def small_font():
    """Returns (pixels rows for a 8 x (8*N) strip, widths list, utf8 extra chars)."""
    glyphs = [glyph(c) for c in ORDER] + [g for _, g in EXTRA]
    pixels = []
    widths = []
    for rows in glyphs:
        cell = [[0] * 8 for _ in range(8)]
        w = glyph_width(rows)
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch == "#" and x < 7 and y < 7:
                    # drop shadow first so the body overwrites it
                    if cell[y + 1][x + 1] == 0:
                        cell[y + 1][x + 1] = 2
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch == "#" and x < 8 and y < 8:
                    cell[y][x] = 1
        if rows is not glyphs[0]:
            pixels.extend(cell)         # Butano font images start at '!' (space has no glyph)
        widths.append(w + 2 if w else 4)
    return pixels, widths, [c for c, _ in EXTRA]


def big_font():
    """16x16 cells: 2x scaled glyph, dark outline, top/bottom gradient and a highlight."""
    glyphs = [glyph(c) for c in ORDER] + [g for _, g in EXTRA]
    pixels = []
    widths = []
    for rows in glyphs:
        cell = [[0] * 16 for _ in range(16)]
        w = glyph_width(rows)
        body = [[False] * 16 for _ in range(16)]
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch == "#":
                    for dy in range(2):
                        for dx in range(2):
                            px, py = 1 + x * 2 + dx, 1 + y * 2 + dy
                            if px < 16 and py < 16:
                                body[py][px] = True
        for y in range(16):
            for x in range(16):
                if body[y][x]:
                    cell[y][x] = 1 if y < 8 else 3
                    if y > 0 and not body[y - 1][x]:
                        cell[y][x] = 4          # top highlight
        for y in range(16):
            for x in range(16):
                if cell[y][x] == 0:
                    for (dx, dy) in ((1, 0), (-1, 0), (0, 1), (0, -1), (1, 1)):
                        nx, ny = x + dx, y + dy
                        if 0 <= nx < 16 and 0 <= ny < 16 and body[ny][nx]:
                            cell[y][x] = 2
                            break
        if rows is not glyphs[0]:
            pixels.extend(cell)
        widths.append(min(16, w * 2 + 3) if w else 8)
    return pixels, widths, [c for c, _ in EXTRA]


