def tiny_font():
    """8x8 cells holding 3x5 glyphs at rows 1..5 (shadow 2..6). Advance = width + 1."""
    glyphs = [tiny_glyph(c) if c != " " else [] for c in ORDER] + [TINY_EXTRA[c] for c, _ in EXTRA]
    pixels = []
    widths = []
    for i, rows in enumerate(glyphs):
        cell = [[0] * 8 for _ in range(8)]
        w = glyph_width(rows)
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch == "#" and cell[y + 2][x + 1] == 0:
                    cell[y + 2][x + 1] = 2
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch == "#":
                    cell[y + 1][x] = 1
        if i:
            pixels.extend(cell)         # Butano font images start at '!' (space has no glyph)
        widths.append(w + 1 if w else 3)
    return pixels, widths, [c for c, _ in EXTRA]
